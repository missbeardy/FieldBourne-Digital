// Run with: node demos/lantern-gully/bake-contours.mjs
// Computes the contour map once and writes it out as ready-made SVG markup, so the browser does no geometry on load.
import { writeFileSync } from 'node:fs'
import { MAP_H, MAP_W, contourLevels, creekPath } from './contours.ts'

function groups(sparse, withLength) {
  return contourLevels
    .map((lv, i) => {
      if (sparse && !lv.major && i % 2 === 1) return ''
      const d = lv.paths.join('')
      if (!d) return ''
      return `<g class="${lv.major ? 'c c-major' : 'c c-minor'}" style="--i:${i}"><path d="${d}"${withLength ? ' pathLength="1"' : ''}/></g>`
    })
    .join('')
}

const creek = `<path class="creek" d="${creekPath}"/>`
const header = '// Generated by bake-contours.mjs. Do not edit by hand.\n'
const hero = groups(true, false) + creek
const map = groups(false, true) + creek

writeFileSync(
  new URL('./contours.baked.ts', import.meta.url),
  `${header}export const MAP_W = ${MAP_W}\nexport const MAP_H = ${MAP_H}\nexport const heroMarkup = ${JSON.stringify(hero)}\n`,
)
// The full map is only needed once the map section is near the screen, so it lives in its own module.
writeFileSync(new URL('./contours.map.ts', import.meta.url), `${header}export const mapMarkup = ${JSON.stringify(map)}\n`)
console.log('hero', hero.length, 'map', map.length)
